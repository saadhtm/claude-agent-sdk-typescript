export function findSubject(idOrName: string): Subject | undefined {
  const key = idOrName.trim()
  return SUBJECTS.find(s => s.id === key || s.name === key || s.name.includes(key))
}

export function findUnit(unitId: string): { subject: Subject; unit: Unit } | undefined {
  for (const subject of SUBJECTS) {
    const unit = subject.units.find(u => u.id === unitId)
    if (unit) return { subject, unit }
  }
  return undefined
}

/** عدد الأسابيع الدراسية التقريبي في كل فصل */
export const WEEKS_PER_TERM = 16

/**
 * توزيع الوحدات على أسابيع الفصل: يقسم أسابيع الفصل بالتساوي على وحدات
 * المادة، فيعرف البوت ما الوحدة "الحالية" في أي أسبوع.
 */
export function unitForWeek(subject: Subject, term: 1 | 2, week: number): Unit {
  const units = subject.units.filter(u => u.term === term)
  const w = Math.min(Math.max(week, 1), WEEKS_PER_TERM)
  const index = Math.min(Math.floor(((w - 1) * units.length) / WEEKS_PER_TERM), units.length - 1)
  return units[index]!
}
