export type TaskKind = 'explain' | 'daily' | 'weekly-notes' | 'weekly-test'

export const TASK_LABELS: Record<TaskKind, string> = {
  explain: 'تلخيص وشرح',
  daily: 'ورقة مراجعة يومية',
  'weekly-notes': 'مراجعة ومذكرة أسبوعية',
  'weekly-test': 'ورقة اختبار أسبوعية',
}

function unitRef(subject: Subject, unit: Unit): string {
  return `المادة: ${subject.name} (معرّف الوحدة: ${unit.id})
الوحدة: ${unit.title} — الفصل الدراسي ${unit.term === 1 ? 'الأول' : 'الثاني'}
أسلوب المادة: ${subject.style}`
}

export function buildTaskPrompt(kind: TaskKind, subject: Subject, unit: Unit, extra?: string): string {
  const ref = unitRef(subject, unit)
  const note = extra?.trim() ? `\nملاحظة من الطالب: ${extra.trim()}` : ''

  switch (kind) {
    case 'explain':
      return `${ref}${note}

اكتب **ملخصاً وشرحاً مبسطاً** للوحدة كاملة بالشكل التالي:
## 🎯 أهداف الوحدة (3–5 نقاط)
## 📚 الشرح المبسط
لكل موضوع: الفكرة الرئيسية في سطر، ثم شرح مبسط، ثم مثال محلول أو تطبيق، ثم 💡 طريقة سهلة للحفظ.
## 📌 أهم التعريفات والقوانين (جدول: المصطلح | المعنى/القانون)
## ⚠️ أخطاء شائعة
## ✅ الخلاصة في 5 أسطر`

    case 'daily':
      return `${ref}${note}

أعدّ **ورقة مراجعة يومية** قصيرة (تُنجز في 15–20 دقيقة) تغطي موضوعاً واحداً أو موضوعين من الوحدة:
## 🗓️ مراجعة اليوم: (اسم الموضوع)
## 🔑 الفكرة في دقيقة (5 نقاط مركزة)
## 📌 احفظ اليوم (تعريفات/قوانين في جدول صغير)
## ✍️ تدريبات سريعة
- 3 أسئلة اختيار من متعدد
- 2 صح وخطأ مع التصحيح
- سؤال "علل" أو مسألة واحدة
## 🔑 الإجابات النموذجية (في آخر الورقة)
## 🌟 تحدي اليوم (سؤال واحد للمتميزين)`

    case 'weekly-notes':
      return `${ref}${note}

أعدّ **مذكرة مراجعة أسبوعية** شاملة للوحدة تصلح للطباعة والمذاكرة قبل الاختبار:
## 🗺️ خريطة الوحدة (مخطط نصي يربط الموضوعات)
## 📖 ملخص كل موضوع (نقاط مركزة)
## 📊 جداول المقارنة المهمة
## 📌 بنك التعريفات والقوانين
## ❓ أسئلة متوقعة مع إجاباتها (10 أسئلة متنوعة: علل، قارن، ماذا يحدث، مسائل)
## 🧠 خطة مذاكرة مقترحة لأيام الأسبوع (الأحد إلى الخميس)`

    case 'weekly-test':
      return `${ref}${note}

أعدّ **ورقة اختبار أسبوعية** على نمط اختبارات وزارة التربية الكويتية للوحدة:
- رأس الورقة: المادة، الوحدة، الزمن (45 دقيقة)، الدرجة الكلية (20 درجة).
## السؤال الأول: اختر الإجابة الصحيحة (5 بنود — 5 درجات)
## السؤال الثاني: ضع علامة (✓) أو (✗) مع تصحيح الخطأ (4 بنود — 4 درجات)
## السؤال الثالث: أكمل / علل / قارن (حسب طبيعة المادة — 5 درجات)
## السؤال الرابع: أسئلة مقالية أو مسائل (6 درجات)
ثم بعد فاصل (---):
## 🔑 نموذج الإجابة وتوزيع الدرجات
## 📈 جدول تقييم ذاتي: الدرجة ← المستوى ← ماذا أراجع`
  }
}

export function buildVoicePrompt(question: string, subject?: Subject): string {
  const ctx = subject ? `(المادة المختارة: ${subject.name})\n` : ''
  return `${ctx}سؤال الطالب الصوتي: ${question}`
}
